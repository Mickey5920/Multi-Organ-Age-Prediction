def load_data(file_path):
    """加载并预处理基础数据 (网页3数据规范)"""
    df = pd.read_csv(
        file_path,
        parse_dates=['Alanine aminotransferase assay date | Instance 0', 'record_time'],
        dtype={'Participant ID': str, 'ICD': 'category'},
        na_values=['', 'NA'],
        infer_datetime_format=True
    )
    # 日期有效性验证
    df = df[df['Alanine aminotransferase assay date | Instance 0'].notna()]
    return df


def process_baseline(df):
    """计算基准时间和有效月份 (网页8时间窗口标准)"""
    # 设置基准时间
    baseline_df = df.groupby('Participant ID')['Alanine aminotransferase assay date | Instance 0'].min().reset_index()
    baseline_df.rename(columns={'Alanine aminotransferase assay date | Instance 0': 'Baseline_Date'}, inplace=True)

    # 合并基准时间
    df = pd.merge(df, baseline_df, on='Participant ID', how='left')

    # 计算月份差异
    df['Months_Diff'] = ((df['record_time'] - df['Baseline_Date']).dt.days // 30).clip(lower=0)
    return df


def exclude_death_cases(df, death_file):
    """排除60个月内死亡的病例 (网页6排除标准)"""
    death_df = pd.read_csv(death_file, usecols=['Participant ID(participant - eid)', 'Date of death'], parse_dates=['Date of death'])
    death_df.rename(columns={'Participant ID(participant - eid)': 'Participant ID'}, inplace=True)
    death_df['Participant ID'] = death_df['Participant ID'].astype(str)

    merged_df = pd.merge(df, death_df, on='Participant ID', how='left')

    # 计算死亡时间差
    merged_df['Death_Month_Diff'] = ((merged_df['Date of death'] - merged_df['Baseline_Date']).dt.days // 30)
    valid_df = merged_df[(merged_df['Death_Month_Diff'] > 60) | (merged_df['Date of death'].isna())]
    return valid_df.drop(columns=['Date of death', 'Death_Month_Diff'])


def classify_participants(df):
    """四向分类核心逻辑 (网页4分类标准)"""
    # 创建分类容器
    classification = defaultdict(list)

    # 预处理标记
    df['Has_ICD'] = df['ICD'].notna()

    # 按参与者分组处理
    grouped = df.groupby('Participant ID')

    for pid, group in grouped:
        baseline_date = group['Baseline_Date'].iloc[0]

        # 全健康判断
        if not group['Has_ICD'].any():
            classification['Full_Health'].append(pid)
            continue

        # 划分时间窗口
        pre_baseline = group[group['record_time'] < baseline_date]
        post_baseline = group[group['record_time'] >= baseline_date]

        # 慢性病检测
        chronic_found = False
        for system, codes in chronic_diseases.items():
            if pre_baseline['ICD'].isin(codes).any():
                classification[system].append(pid)
                chronic_found = True
                break

        if chronic_found: continue

        # 其他疾病判断
        if pre_baseline['Has_ICD'].any():
            classification['Other_Disease'].append(pid)
            continue

        # 健康转病判断
        if post_baseline['Has_ICD'].any():
            classification['Health'].append(pid)

    return classification


def save_classification(results, output_dir):
    """保存分类结果到CSV (网页9输出规范)"""
    # 保存各系统文件
    for system in chronic_diseases.keys():
        if system in results:
            pd.DataFrame({'Participant ID': results[system]}) \
                .to_csv(f"{output_dir}/{system}_Group.csv", index=False)

    # 保存其他类别
    pd.DataFrame({'Participant ID': results.get('Other_Disease', [])}) \
        .to_csv(f"{output_dir}/Other_Disease_Group.csv", index=False)
    pd.DataFrame({'Participant ID': results.get('Health', [])}) \
        .to_csv(f"{output_dir}/Health_Group.csv", index=False)
    pd.DataFrame({'Participant ID': results.get('Full_Health', [])}) \
        .to_csv(f"{output_dir}/Full_Health_Group.csv", index=False)


def classify_participants_strict(df):
    """更精细的分类逻辑：
    - 完全健康
    - 七系统各自的健康（未在该系统中患病）
    - 其他疾病
    - 健康转病
    """

    classification = defaultdict(list)
    grouped = df.groupby('Participant ID')

    for pid, group in grouped:
        baseline_date = group['Baseline_Date'].iloc[0]
        pre = group[group['record_time'] < baseline_date]
        post = group[group['record_time'] >= baseline_date]

        pre_icds = set(pre['ICD'].dropna().unique())
        post_icds = set(post['ICD'].dropna().unique())

        # 完全健康：基准前无ICD，且基准后也无ICD
        if not pre_icds and not post_icds:
            classification['Full_Health'].append(pid)
            continue

        # 七系统健康（指：没患过该系统，但有其他系统病）
        system_matched = False
        for system, codes in chronic_diseases.items():
            codes_set = set(codes)
            if pre_icds & codes_set:
                classification[system].append(pid)
                system_matched = True
                break

        if system_matched:
            continue

        # 如果ICD都不在七大系统中
        all_defined_codes = set().union(*chronic_diseases.values())
        if pre_icds and pre_icds.isdisjoint(all_defined_codes):
            classification['Other_Disease'].append(pid)
            continue

        # 健康后期转病
        # 基准前无 ICD，需判断 post 是否有
        # 健康转病：基准前无ICD，基准后有ICD
        if not pre_icds and post_icds:
            classification['Health'].append(pid)
            continue

    # === 七器官健康判断 ===
    # 只要在该系统中无ICD，即使有其他系统病，也可加入其 Health 组
    for pid, group in grouped:
        pre_icds = set(group[group['record_time'] < group['Baseline_Date'].iloc[0]]['ICD'].dropna().unique())
        if not pre_icds:
            continue

        for system, codes in chronic_diseases.items():
            if not (pre_icds & set(codes)):
                classification[f"{system}_Health"].append(pid)

    return classification


